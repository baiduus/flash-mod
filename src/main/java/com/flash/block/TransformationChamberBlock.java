package com.flash.block;

import com.flash.registry.ModBlockEntities;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.InteractionHand;
import net.minecraft.world.InteractionResult;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.item.context.BlockPlaceContext;
import net.minecraft.world.level.BlockGetter;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.BaseEntityBlock;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Mirror;
import net.minecraft.world.level.block.RenderShape;
import net.minecraft.world.level.block.Rotation;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.block.entity.BlockEntityTicker;
import net.minecraft.world.level.block.entity.BlockEntityType;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;
import net.minecraft.world.level.block.state.properties.BooleanProperty;
import net.minecraft.world.level.block.state.properties.DirectionProperty;
import net.minecraft.world.phys.AABB;
import net.minecraft.world.phys.BlockHitResult;
import net.minecraft.world.phys.Vec3;
import net.minecraft.world.phys.shapes.CollisionContext;
import net.minecraft.world.phys.shapes.Shapes;
import net.minecraft.world.phys.shapes.VoxelShape;

/**
 * The main transformation chamber. One controller block owns the whole large
 * structure (stepped base, opening, columns, header, roof and side technology).
 * The rendered model extends around the controller; the controller cell is the
 * front-left column of the machine as seen from the front.
 *
 * <p>The model (generated by {@code tools/gen_machine.py}) is about 4.3 blocks
 * wide, 5.2 blocks tall and 4.4 blocks deep. All geometry constants below are
 * written in "model space" for {@code facing=south}: +x is east, +z is south, and
 * the controller cell is {@code [0,1] x [0,1]}. The blockstate rotates the model
 * for the other facings and {@link #toWorld} applies the same rotation to
 * points, so the cabin centre, the exit point and the selection box always
 * match what is drawn.</p>
 */
public class TransformationChamberBlock extends BaseEntityBlock {

    public static final BooleanProperty ACTIVE = BooleanProperty.create("active");
    public static final DirectionProperty FACING = DirectionProperty.create(
            "facing",
            Direction.NORTH, Direction.EAST, Direction.SOUTH, Direction.WEST
    );

    /** Height of the cabin floor above the controller block (top of the floor plates). */
    public static final double FLOOR_HEIGHT = 0.5D;
    /** Total height of the model. */
    public static final double MODEL_HEIGHT = 5.2D;

    /** Model-space footprint (facing=south) of everything that is drawn. */
    private static final double MODEL_MIN_X = 0.0D;
    private static final double MODEL_MAX_X = 4.34D;
    private static final double MODEL_MIN_Z = -2.78D;
    private static final double MODEL_MAX_Z = 1.58D;

    /** Cabin centre (model space): design X = 2.0, depth 0.95 behind the front plane. */
    private static final double CABIN_X = 2.0D;
    private static final double CABIN_Z = 0.05D;
    /** A point just outside the front steps, used as the exit position. */
    private static final double EXIT_X = 2.0D;
    private static final double EXIT_Z = 2.2D;

    /**
     * Collision stays on the controller cell: it is the solid left column and
     * casing of the machine. The opening is outside this cell, so the player
     * teleported into the cabin never starts inside a collision box. Model-space
     * box (facing=south): x 0.15..1.0, z 0..1, up to the top of the opening.
     */
    private static final double COLLISION_MIN_X = 0.15D;
    private static final double COLLISION_MAX_X = 1.0D;
    private static final double COLLISION_HEIGHT = 3.8D;

    public TransformationChamberBlock(Properties properties) {
        super(properties);
        this.registerDefaultState(this.stateDefinition.any()
                .setValue(ACTIVE, Boolean.FALSE)
                .setValue(FACING, Direction.NORTH));
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(ACTIVE, FACING);
    }

    @Override
    public BlockState getStateForPlacement(BlockPlaceContext context) {
        return this.defaultBlockState()
                .setValue(FACING, context.getHorizontalDirection().getOpposite());
    }

    @Override
    public BlockEntity newBlockEntity(BlockPos pos, BlockState state) {
        return new TransformationChamberBlockEntity(pos, state);
    }

    @Override
    public <T extends BlockEntity> BlockEntityTicker<T> getTicker(Level level, BlockState state,
                                                                 BlockEntityType<T> type) {
        if (level.isClientSide) {
            return null;
        }
        return createTickerHelper(
                type,
                ModBlockEntities.TRANSFORMATION_CHAMBER.get(),
                TransformationChamberBlockEntity::serverTick
        );
    }

    @Override
    public InteractionResult use(BlockState state, Level level, BlockPos pos, Player player,
                                 InteractionHand hand, BlockHitResult hit) {
        if (player.isShiftKeyDown()) {
            return InteractionResult.PASS;
        }
        if (level.isClientSide) {
            return InteractionResult.SUCCESS;
        }
        if (player instanceof ServerPlayer serverPlayer
                && level.getBlockEntity(pos) instanceof TransformationChamberBlockEntity chamber) {
            chamber.tryEnter(serverPlayer);
            return InteractionResult.CONSUME;
        }
        return InteractionResult.PASS;
    }

    @Override
    public void onRemove(BlockState state, Level level, BlockPos pos, BlockState newState, boolean isMoving) {
        if (!state.is(newState.getBlock()) && !level.isClientSide
                && level.getBlockEntity(pos) instanceof TransformationChamberBlockEntity chamber) {
            chamber.onChamberRemoved();
        }
        super.onRemove(state, level, pos, newState, isMoving);
    }

    @Override
    public VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        Direction facing = state.getValue(FACING);
        return rotatedBox(facing, MODEL_MIN_X, MODEL_MIN_Z, MODEL_MAX_X, MODEL_MAX_Z, MODEL_HEIGHT);
    }

    @Override
    public VoxelShape getCollisionShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        Direction facing = state.getValue(FACING);
        return rotatedBox(facing, COLLISION_MIN_X, 0.0D, COLLISION_MAX_X, 1.0D, COLLISION_HEIGHT);
    }

    // ------------------------------------------------------------------
    // Model-space helpers (shared with the block entity and the client)
    // ------------------------------------------------------------------

    /**
     * Rotates a model-space point (facing=south) about the controller cell
     * centre, exactly like the blockstate {@code y} rotation (south 0, west 90,
     * north 180, east 270). Returns {x, z} relative to the controller cell.
     */
    private static double[] rotate(Direction facing, double x, double z) {
        return switch (facing) {
            case WEST -> new double[] {1.0D - z, x};
            case NORTH -> new double[] {1.0D - x, 1.0D - z};
            case EAST -> new double[] {z, 1.0D - x};
            default -> new double[] {x, z};
        };
    }

    private static VoxelShape rotatedBox(Direction facing, double minX, double minZ,
                                         double maxX, double maxZ, double height) {
        double[] a = rotate(facing, minX, minZ);
        double[] b = rotate(facing, maxX, maxZ);
        return Shapes.box(Math.min(a[0], b[0]), 0.0D, Math.min(a[1], b[1]),
                Math.max(a[0], b[0]), height, Math.max(a[1], b[1]));
    }

    /** World position of a model-space point at the given height above the controller block. */
    public static Vec3 toWorld(BlockPos pos, BlockState state, double x, double y, double z) {
        double[] r = rotate(state.getValue(FACING), x, z);
        return new Vec3(pos.getX() + r[0], pos.getY() + y, pos.getZ() + r[1]);
    }

    /** Centre of the cabin floor, where the occupant stands. */
    public static Vec3 cabinFloorCenter(BlockPos pos, BlockState state) {
        return toWorld(pos, state, CABIN_X, FLOOR_HEIGHT, CABIN_Z);
    }

    /** Point in front of the entrance steps where a leaving player is placed. */
    public static Vec3 exitPoint(BlockPos pos, BlockState state) {
        return toWorld(pos, state, EXIT_X, FLOOR_HEIGHT, EXIT_Z);
    }

    /** Everything that is drawn, in world coordinates (used for targeting). */
    public static AABB footprint(BlockPos pos, BlockState state) {
        Vec3 a = toWorld(pos, state, MODEL_MIN_X, 0.0D, MODEL_MIN_Z);
        Vec3 b = toWorld(pos, state, MODEL_MAX_X, MODEL_HEIGHT, MODEL_MAX_Z);
        return new AABB(a.x, a.y, a.z, b.x, b.y, b.z);
    }

    @Override
    public RenderShape getRenderShape(BlockState state) {
        return RenderShape.MODEL;
    }

    @Override
    public BlockState rotate(BlockState state, Rotation rotation) {
        return state.setValue(FACING, rotation.rotate(state.getValue(FACING)));
    }

    @Override
    public BlockState mirror(BlockState state, Mirror mirror) {
        return state.rotate(mirror.getRotation(state.getValue(FACING)));
    }
}
