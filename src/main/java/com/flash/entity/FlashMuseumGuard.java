package com.flash.entity;

import com.flash.FlashMod;
import net.minecraft.core.registries.Registries;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.InteractionResult;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.decoration.ArmorStand;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.level.levelgen.structure.Structure;
import net.minecraftforge.event.entity.living.LivingAttackEvent;
import net.minecraftforge.event.entity.player.PlayerInteractEvent;
import net.minecraftforge.eventbus.api.EventPriority;
import net.minecraftforge.eventbus.api.SubscribeEvent;
import net.minecraftforge.fml.common.Mod;

/**
 * Every armour stand inside a Flash Museum is an exhibit: in survival its armour
 * cannot be taken or swapped and the stand cannot be broken. It works by position,
 * so stands of museums generated by older versions of the mod are protected too.
 * Creative players can still edit them. Outside the museum nothing changes.
 */
@Mod.EventBusSubscriber(modid = FlashMod.MODID)
public final class FlashMuseumGuard {

    private static final ResourceKey<Structure> MUSEUM = ResourceKey.create(Registries.STRUCTURE,
            new ResourceLocation(FlashMod.MODID, "flash_museum"));
    private static final String CHECKED = "flash_museum_checked";

    private FlashMuseumGuard() {
    }

    /** True for a stand in a museum (the answer is remembered on the entity as a tag). */
    public static boolean isExhibit(Entity entity) {
        if (!(entity instanceof ArmorStand stand)) {
            return false;
        }
        if (stand.getTags().contains(FlashSuitStand.MUSEUM_TAG)) {
            return true;
        }
        if (!(stand.level() instanceof ServerLevel level) || stand.getTags().contains(CHECKED)) {
            return false;
        }
        stand.addTag(CHECKED);
        boolean inside = level.structureManager()
                .getStructureWithPieceAt(stand.blockPosition(), MUSEUM).isValid();
        if (inside) {
            stand.addTag(FlashSuitStand.MUSEUM_TAG);
            stand.setInvulnerable(true);
        }
        return inside;
    }

    @SubscribeEvent(priority = EventPriority.HIGHEST)
    public static void onInteractAt(PlayerInteractEvent.EntityInteractSpecific event) {
        if (block(event.getEntity(), event.getTarget())) {
            event.setCanceled(true);
            event.setCancellationResult(InteractionResult.FAIL);
        }
    }

    @SubscribeEvent(priority = EventPriority.HIGHEST)
    public static void onInteract(PlayerInteractEvent.EntityInteract event) {
        if (block(event.getEntity(), event.getTarget())) {
            event.setCanceled(true);
            event.setCancellationResult(InteractionResult.FAIL);
        }
    }

    @SubscribeEvent(priority = EventPriority.HIGHEST)
    public static void onAttack(LivingAttackEvent event) {
        if (event.getEntity() instanceof ArmorStand && !event.getEntity().level().isClientSide
                && isExhibit(event.getEntity())
                && !(event.getSource().getEntity() instanceof Player player && player.getAbilities().instabuild)) {
            event.setCanceled(true);
        }
    }

    private static boolean block(Player player, Entity target) {
        if (player.getAbilities().instabuild || !(target instanceof ArmorStand)) {
            return false;
        }
        if (player.level().isClientSide) {
            return false; // the client cannot see structures; the server decides and keeps the armour
        }
        if (!isExhibit(target)) {
            return false;
        }
        player.displayClientMessage(Component.translatable("message.flash.museum_locked"), true);
        return true;
    }
}
